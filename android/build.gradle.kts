// NoSuchMethodError List.removeLast() inside JavaDocParser. Skip vital lint for
// release AAB so Play CI can ship; app/plugin source lint still runs in CI analyze.
subprojects {
    tasks.configureEach {
        if (name.startsWith("lintVital")) {
            enabled = false
        }
    }
}

